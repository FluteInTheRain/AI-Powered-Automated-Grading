#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Regenerate the golden files under tests/golden/ after a DELIBERATE change.

    python3 scripts/update_golden.py

Rewrites tests/golden/prompts.json (rendered prompts and hashes) and the
`expected` block of every case in tests/golden/replay_set.json. It never touches
the frozen inputs or the recorded responses: those are edited by hand.

Then read `git diff tests/golden/` and commit it with the change that caused it.
No model and no network are used. See docs/golden-regression.md.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tests" / "golden"))
import golden_support as g  # noqa: E402


def dump(path: Path, obj) -> None:
    path.write_text(json.dumps(obj, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def main() -> None:
    prompts = {
        "_README": "Rendered text of every prompts/*.txt for fixed inputs, with SHA-256. "
                   "Generated by scripts/update_golden.py; do not edit by hand.",
        "prompts": g.render_prompts(),
    }
    old = json.loads(g.PROMPTS_GOLDEN.read_text(encoding="utf-8")) if g.PROMPTS_GOLDEN.exists() else {}
    changed = [n for n, v in prompts["prompts"].items() if old.get("prompts", {}).get(n) != v]
    dump(g.PROMPTS_GOLDEN, prompts)
    print(f"prompts.json: {len(prompts['prompts'])} prompts, changed: {', '.join(changed) or 'none'}")

    replay = g.load_replay()
    for case in replay["cases"]:
        new = g.replay_one(case)
        if case.get("expected") not in (None, new):
            print(f"replay {case['id']}: {case['expected']['final_score_0_to_100']} -> {new['final_score_0_to_100']}")
        case["expected"] = new
    dump(g.REPLAY_GOLDEN, replay)
    print(f"replay_set.json: {len(replay['cases'])} cases")
    print("Now review `git diff tests/golden/` before committing.")


if __name__ == "__main__":
    main()
