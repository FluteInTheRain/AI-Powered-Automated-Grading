#!/usr/bin/env python3
"""Generate app-worker/seed/bank.sql (the system question bank) from data/problems.py.

Never hand-edit the SQL: edit data/problems.py and rerun this script.
Apply with: npx wrangler d1 execute teacher-app --remote --file seed/bank.sql
"""
import ast
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
for p in (ROOT, ROOT / "src", ROOT / "data"):
    sys.path.insert(0, str(p))

from grader import sandbox  # noqa: E402
from problems import PROBLEMS  # noqa: E402
from server.rules import starter_code  # noqa: E402

OUT = ROOT / "app-worker" / "seed" / "bank.sql"
DIFFICULTIES = {"easy", "medium", "hard"}


def _param_names(code: str, func_name: str) -> list:
    for node in ast.parse(code).body:
        if isinstance(node, ast.FunctionDef) and node.name == func_name:
            return [a.arg for a in node.args.args]
    raise ValueError(f"def {func_name} not found in the reference solution")


def build_rows() -> list:
    rows = []
    for p in PROBLEMS:
        reference = p["submissions"][0]["code"].strip() + "\n"
        cases = [
            # json round-trip: tuples become lists, as they are stored and compared later.
            {"args": json.loads(json.dumps(list(args))), "expected": json.loads(json.dumps(expected)),
             # Only the first case is public; one case alone stays hidden so grading has a hidden case.
             "is_public": i == 0 and len(p["test_cases"]) > 1}
            for i, (args, expected) in enumerate(p["test_cases"])
        ]
        row = {
            "id": f"bank:{p['id']}", "statement": p["statement"], "func_name": p["func_name"],
            "param_names": _param_names(reference, p["func_name"]), "rubric": dict(p["rubric"]),
            "reference_solution": reference, "test_cases": cases,
            "starter_code": starter_code(p["func_name"], _param_names(reference, p["func_name"])),
            "title": p["title"], "category": p["category"], "difficulty": p["difficulty"],
        }
        if not 1 <= len(row["title"]) <= 80 or not 1 <= len(row["category"]) <= 40 or row["difficulty"] not in DIFFICULTIES:
            raise ValueError(f"{row['id']}: invalid title, category or difficulty")
        if sum(row["rubric"].values()) != 100:
            raise ValueError(f"{row['id']}: rubric does not sum to 100")
        res = sandbox.run_submission(reference, p["func_name"],
                                     [(tuple(c["args"]), c["expected"]) for c in cases])
        if res["status"] != "ran" or res["pass_rate"] != 1.0:
            raise ValueError(f"{row['id']}: reference fails its own cases: {res}")
        rows.append(row)
    return rows


def _q(value) -> str:
    return "'" + str(value).replace("'", "''") + "'"


def render_sql(rows: list) -> str:
    out = ["-- GENERATED by scripts/export_bank_seed.py from data/problems.py. Do not edit."]
    for r in rows:
        out.append(
            # Upsert, not INSERT OR REPLACE: exams reference these rows, so an existing problem keeps its statement,
            # tests and rubric and only gets its catalog metadata refreshed.
            "INSERT INTO problems (id, owner_teacher_id, visibility, statement, func_name,"
            " param_names, rubric, reference_solution, test_cases, starter_code, created_at, title, category, difficulty) VALUES ("
            + ", ".join([_q(r["id"]), "NULL", "'system'", _q(r["statement"]), _q(r["func_name"]),
                         _q(json.dumps(r["param_names"])), _q(json.dumps(r["rubric"])),
                         _q(r["reference_solution"]), _q(json.dumps(r["test_cases"])),
                         _q(r["starter_code"]), "'2026-01-01T00:00:00+00:00'",
                         _q(r["title"]), _q(r["category"]), _q(r["difficulty"])])
            + ") ON CONFLICT(id) DO UPDATE SET title = excluded.title, category = excluded.category,"
            " difficulty = excluded.difficulty;"
        )
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    OUT.write_text(render_sql(build_rows()))
    print(f"wrote {OUT}")
